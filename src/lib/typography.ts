/*
	Типографіка тексту: нерозривні пробіли там, де розрив рядка читається погано.
	«з / 1:00», «0,9 / мм», «уночі / — +14°» — так не має бути ні на телефоні, ні на компʼютері.
*/

const NBSP = ' ';

// Короткі прийменники й сполучники тримаються з наступним словом, а не висять у кінці рядка.
// Lookbehind дивиться на вихідний рядок, тож ланцюжки на кшталт «а до» теж склеюються
const SHORT_WORDS =
	/(?<=^|[\s («])(з|зі|із|і|й|в|у|а|та|до|на|о|об|від|за|по|про|не|як|що)\s+/giu;

// Число не відривається від одиниці виміру
const NUMBER_UNIT = /(\d)\s+(мм|м\/с|км|год|хв|%)/gu;

export function typograph(text: string): string {
	return text
		.replace(SHORT_WORDS, `$1${NBSP}`)
		.replace(NUMBER_UNIT, `$1${NBSP}$2`)
		.replace(/\s+—/gu, `${NBSP}—`);
}
